/// `autox_flood`.
pub fn autox_flood(
    state: &mut AutoxState,
    ax: &mut Autox,
    view: &AutoxView,
    native: &mut dyn AutoxNativeBoundary,
) -> i32 {
    let section = native.current_section(view.zmouse.round() as i32, view.ushort_store != 0);
    let Some(image) = section else {
        return 0;
    };
    state.auto_image = image;
    if state.auto_image.len() < view.xysize || ax.data.len() < view.xysize || ax.listsize == 0 {
        return 0;
    }
    let mut x = view.xmouse as i32;
    let mut y = view.ymouse as i32;
    if x < 0 || y < 0 || x >= view.xsize || y >= view.ysize {
        return 0;
    }
    let mut threshold = ax.threshold + 1;
    if view.depth == 8 && view.rgba == 0 {
        threshold =
            ((view.rampsize as f32 / 256. * threshold as f32) + view.rampbase as f32) as i32;
    }
    ax.thresh_used = threshold as f32 - 0.5;
    let index = (x + y * view.xsize) as usize;
    ax.reverse = i32::from((state.auto_image[index] as i32) < threshold);
    ax.xlist[0] = x;
    ax.ylist[0] = y;
    ax.data[index] |= AUTOX_CHECK;
    let mut ringnext = 0usize;
    let mut ringfree = 1usize;
    let neighflag = AUTOX_FLOOD | AUTOX_CHECK;
    while ringnext != ringfree {
        x = ax.xlist[ringnext];
        y = ax.ylist[ringnext];
        let point = (x + y * view.xsize) as usize;
        let test = if ax.reverse != 0 {
            (state.auto_image[point] as i32) < threshold || ax.data[point] & AUTOX_BLACK != 0
        } else {
            (state.auto_image[point] as i32 >= threshold || ax.data[point] & AUTOX_WHITE != 0)
                && ax.data[point] & AUTOX_BLACK == 0
        };
        if test {
            ax.data[point] |= AUTOX_FLOOD;
            if x > 0 && ax.data[point - 1] & neighflag == 0 {
                ax.xlist[ringfree] = x - 1;
                ax.ylist[ringfree] = y;
                ringfree = (ringfree + 1) % ax.listsize;
                ax.data[point - 1] |= AUTOX_CHECK;
            }
            if x < view.xsize - 1 && ax.data[point + 1] & neighflag == 0 {
                ax.xlist[ringfree] = x + 1;
                ax.ylist[ringfree] = y;
                ringfree = (ringfree + 1) % ax.listsize;
                ax.data[point + 1] |= AUTOX_CHECK;
            }
            if y > 0 && ax.data[point - view.xsize as usize] & neighflag == 0 {
                ax.xlist[ringfree] = x;
                ax.ylist[ringfree] = y - 1;
                ringfree = (ringfree + 1) % ax.listsize;
                ax.data[point - view.xsize as usize] |= AUTOX_CHECK;
            }
            if y < view.ysize - 1 && ax.data[point + view.xsize as usize] & neighflag == 0 {
                ax.xlist[ringfree] = x;
                ax.ylist[ringfree] = y + 1;
                ringfree = (ringfree + 1) % ax.listsize;
                ax.data[point + view.xsize as usize] |= AUTOX_CHECK;
            }
            if ax.diagonal != 0 {
                if x > 0 && y > 0 && ax.data[point - 1 - view.xsize as usize] & neighflag == 0 {
                    ax.xlist[ringfree] = x - 1;
                    ax.ylist[ringfree] = y - 1;
                    ringfree = (ringfree + 1) % ax.listsize;
                    ax.data[point - 1 - view.xsize as usize] |= AUTOX_CHECK;
                }
                if x < view.xsize - 1
                    && y > 0
                    && ax.data[point + 1 - view.xsize as usize] & neighflag == 0
                {
                    ax.xlist[ringfree] = x + 1;
                    ax.ylist[ringfree] = y - 1;
                    ringfree = (ringfree + 1) % ax.listsize;
                    ax.data[point + 1 - view.xsize as usize] |= AUTOX_CHECK;
                }
                if x > 0
                    && y < view.ysize - 1
                    && ax.data[point - 1 + view.xsize as usize] & neighflag == 0
                {
                    ax.xlist[ringfree] = x - 1;
                    ax.ylist[ringfree] = y + 1;
                    ringfree = (ringfree + 1) % ax.listsize;
                    ax.data[point - 1 + view.xsize as usize] |= AUTOX_CHECK;
                }
                if x < view.xsize - 1
                    && y < view.ysize - 1
                    && ax.data[point + 1 + view.xsize as usize] & neighflag == 0
                {
                    ax.xlist[ringfree] = x + 1;
                    ax.ylist[ringfree] = y + 1;
                    ringfree = (ringfree + 1) % ax.listsize;
                    ax.data[point + 1 + view.xsize as usize] |= AUTOX_CHECK;
                }
            }
        }
        ax.data[point] &= !AUTOX_CHECK;
        ringnext = (ringnext + 1) % ax.listsize;
    }
    1
}

/// `autox_clear`.
pub fn autox_clear(ax: &mut Autox, bit: u8) {
    for point in &mut ax.data {
        *point &= !bit;
    }
}

