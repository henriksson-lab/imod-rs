//! Lookup-table transforms from `IMOD/raptor/opencv/cxlut.cpp`.
//!
//! The C entry points operate on byte pointers and byte strides.  This
//! translation retains byte strides at the corresponding low-level entry
//! points, but uses slices and owned matrices rather than untyped pointers.

/// `CvSize` for the LUT kernels.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct LutSize {
    pub width: usize,
    pub height: usize,
}

/// Safe replacement for the `CvStatus` failures reachable from this unit.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LutError {
    BadArgument,
    UnmatchedSizes,
    UnmatchedFormats,
    UnsupportedFormat,
}

/// An owned, interleaved matrix accepted by [`cv_lut`].
#[derive(Clone, Debug, PartialEq)]
pub struct LutMatrix<T> {
    pub rows: usize,
    pub columns: usize,
    pub channels: usize,
    pub data: Vec<T>,
}

/// The two source depths accepted by the original `cvLUT` API.
#[derive(Clone, Debug, PartialEq)]
pub enum LutSource {
    Unsigned(LutMatrix<u8>),
    Signed(LutMatrix<i8>),
}

macro_rules! define_lut_c1 {
    ($name:ident, $type:ty) => {
        /// C1 LUT kernel generated by `ICV_DEF_LUT_FUNC_8U_CN`.
        pub fn $name(
            src: &[u8],
            src_step: usize,
            dst: &mut [$type],
            dst_step: usize,
            size: LutSize,
            lut: &[$type],
        ) -> Result<(), LutError> {
            if lut.len() < 256
                || src_step < size.width
                || dst_step % core::mem::size_of::<$type>() != 0
            {
                return Err(LutError::BadArgument);
            }
            let dst_step = dst_step / core::mem::size_of::<$type>();
            if src.len() < size.height.saturating_sub(1).saturating_mul(src_step) + size.width
                || dst.len() < size.height.saturating_sub(1).saturating_mul(dst_step) + size.width
            {
                return Err(LutError::BadArgument);
            }
            for row in 0..size.height {
                let src_row = row * src_step;
                let dst_row = row * dst_step;
                let mut column = 0;
                while column + 4 <= size.width {
                    dst[dst_row + column] = lut[src[src_row + column] as usize];
                    dst[dst_row + column + 1] = lut[src[src_row + column + 1] as usize];
                    dst[dst_row + column + 2] = lut[src[src_row + column + 2] as usize];
                    dst[dst_row + column + 3] = lut[src[src_row + column + 3] as usize];
                    column += 4;
                }
                while column < size.width {
                    dst[dst_row + column] = lut[src[src_row + column] as usize];
                    column += 1;
                }
            }
            Ok(())
        }
    };
}

macro_rules! define_lut_cn_u8 {
    ($name:ident, $channels:expr) => {
        /// Interleaved `u8` LUT kernel generated by `ICV_DEF_LUT_FUNC_8U_CN`.
        pub fn $name(
            src: &[u8],
            src_step: usize,
            dst: &mut [u8],
            dst_step: usize,
            size: LutSize,
            lut: &[u8],
        ) -> Result<(), LutError> {
            let width = size
                .width
                .checked_mul($channels)
                .ok_or(LutError::BadArgument)?;
            if lut.len() < 256 * $channels
                || src_step < width
                || dst_step < width
                || src.len() < size.height.saturating_sub(1).saturating_mul(src_step) + width
                || dst.len() < size.height.saturating_sub(1).saturating_mul(dst_step) + width
            {
                return Err(LutError::BadArgument);
            }
            for row in 0..size.height {
                let src_row = row * src_step;
                let dst_row = row * dst_step;
                for column in (0..width).step_by($channels) {
                    for channel in 0..$channels {
                        dst[dst_row + column + channel] =
                            lut[src[src_row + column + channel] as usize * $channels + channel];
                    }
                }
            }
            Ok(())
        }
    };
}

macro_rules! define_lut_cn {
    ($name:ident, $type:ty) => {
        /// General-channel LUT kernel generated by `ICV_DEF_LUT_FUNC_8U`.
        pub fn $name(
            src: &[u8],
            src_step: usize,
            dst: &mut [$type],
            dst_step: usize,
            size: LutSize,
            lut: &[$type],
            channels: usize,
        ) -> Result<(), LutError> {
            let width = size
                .width
                .checked_mul(channels)
                .ok_or(LutError::BadArgument)?;
            if channels == 0
                || lut.len() < 256 * channels
                || src_step < width
                || dst_step % core::mem::size_of::<$type>() != 0
            {
                return Err(LutError::BadArgument);
            }
            let dst_step = dst_step / core::mem::size_of::<$type>();
            if src.len() < size.height.saturating_sub(1).saturating_mul(src_step) + width
                || dst.len() < size.height.saturating_sub(1).saturating_mul(dst_step) + width
            {
                return Err(LutError::BadArgument);
            }
            for row in 0..size.height {
                let src_row = row * src_step;
                let dst_row = row * dst_step;
                for column in (0..width).step_by(channels) {
                    for channel in 0..channels {
                        dst[dst_row + column + channel] =
                            lut[src[src_row + column + channel] as usize * channels + channel];
                    }
                }
            }
            Ok(())
        }
    };
}

