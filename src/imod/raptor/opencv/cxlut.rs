/// Owned safe translation of `cvLUT`.
pub fn cv_lut<T: Copy>(
    source: &LutSource,
    destination: &mut LutMatrix<T>,
    table: &LutMatrix<T>,
) -> Result<(), LutError> {
    let (rows, columns, channels, source_data) = match source {
        LutSource::Unsigned(matrix)
            if matrix
                .rows
                .checked_mul(matrix.columns)
                .and_then(|count| count.checked_mul(matrix.channels))
                == Some(matrix.data.len()) =>
        {
            (
                matrix.rows,
                matrix.columns,
                matrix.channels,
                matrix
                    .data
                    .iter()
                    .map(|&value| value as usize)
                    .collect::<Vec<_>>(),
            )
        }
        LutSource::Signed(matrix)
            if matrix
                .rows
                .checked_mul(matrix.columns)
                .and_then(|count| count.checked_mul(matrix.channels))
                == Some(matrix.data.len()) =>
        {
            (
                matrix.rows,
                matrix.columns,
                matrix.channels,
                matrix
                    .data
                    .iter()
                    .map(|&value| (value as i16 + 128) as usize)
                    .collect::<Vec<_>>(),
            )
        }
        _ => return Err(LutError::BadArgument),
    };
    if destination
        .rows
        .checked_mul(destination.columns)
        .and_then(|count| count.checked_mul(destination.channels))
        != Some(destination.data.len())
        || table
            .rows
            .checked_mul(table.columns)
            .and_then(|count| count.checked_mul(table.channels))
            != Some(table.data.len())
        || destination.rows != rows
        || destination.columns != columns
    {
        return Err(LutError::UnmatchedSizes);
    }
    if destination.channels != channels {
        return Err(LutError::UnmatchedFormats);
    }
    if table
        .rows
        .checked_mul(table.columns)
        .and_then(|count| count.checked_mul(table.channels))
        != Some(256 * table.channels)
        || (table.channels != 1 && table.channels != channels)
    {
        return Err(LutError::BadArgument);
    }
    for (index, &value) in source_data.iter().enumerate() {
        let channel = index % channels;
        destination.data[index] =
            table.data[value * table.channels + if table.channels == 1 { 0 } else { channel }];
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn c1_kernels_preserve_rows_and_byte_strides() {
        let source = [0, 2, 3, 0, 1, 4, 5, 0];
        let mut destination = [99_u16; 8];
        let table: Vec<u16> = (0..256).map(|value| value * 11).collect();
        icv_lut_transform8u_16u_c1r(
            &source,
            4,
            &mut destination,
            8,
            LutSize {
                width: 3,
                height: 2,
            },
            &table,
        )
        .unwrap();
        assert_eq!(destination, [0, 22, 33, 99, 11, 44, 55, 99]);
    }

    #[test]
    fn interleaved_kernels_select_each_channel_table() {
        let source = [1, 2, 3, 4, 5, 6];
        let mut destination = [0; 6];
        let mut table = vec![0; 256 * 3];
        for value in 0..256 {
            for channel in 0..3 {
                table[value * 3 + channel] = (value + channel * 40) as u8;
            }
        }
        icv_lut_transform8u_8u_c3r(
            &source,
            6,
            &mut destination,
            6,
            LutSize {
                width: 2,
                height: 1,
            },
            &table,
        )
        .unwrap();
        assert_eq!(destination, [1, 42, 83, 4, 45, 86]);
    }

    #[test]
    fn cv_lut_handles_signed_input_with_the_source_shuffle() {
        let source = LutSource::Signed(LutMatrix {
            rows: 1,
            columns: 3,
            channels: 1,
            data: vec![-128, 0, 127],
        });
        let table = LutMatrix {
            rows: 1,
            columns: 256,
            channels: 1,
            data: (0..256).map(|value| value as i32).collect(),
        };
        let mut destination = LutMatrix {
            rows: 1,
            columns: 3,
            channels: 1,
            data: vec![0_i32; 3],
        };
        cv_lut(&source, &mut destination, &table).unwrap();
        assert_eq!(destination.data, [0, 128, 255]);
    }
}
