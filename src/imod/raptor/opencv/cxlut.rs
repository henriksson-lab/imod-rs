/// Header inline alias for the `i8` destination C1 kernel.
pub fn icv_lut_transform8u_8s_c1r(
    src: &[u8],
    src_step: usize,
    dst: &mut [i8],
    dst_step: usize,
    size: LutSize,
    lut: &[i8],
) -> Result<(), LutError> {
    if lut.len() < 256
        || src_step < size.width
        || dst_step < size.width
        || src.len() < size.height.saturating_sub(1).saturating_mul(src_step) + size.width
        || dst.len() < size.height.saturating_sub(1).saturating_mul(dst_step) + size.width
    {
        return Err(LutError::BadArgument);
    }
    for row in 0..size.height {
        for column in 0..size.width {
            dst[row * dst_step + column] = lut[src[row * src_step + column] as usize];
        }
    }
    Ok(())
}

